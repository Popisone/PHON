"""Reck 1994 decomposition demo.

Generates static .phon source + .npy targets for:
  - 3x3 DFT  (exact, well-known unitary)
  - 4x4 random unitary (seed=42)
  - 8x8 random unitary (seed=42)

Verifies each by two methods:
  1. reconstruct_from_ops (direct matrix reconstruction)
  2. PHON simulator (end-to-end via generated .phon source)

Run:
  python examples/reck_demo.py
"""
import sys
from pathlib import Path
import numpy as np

# Add src to path when running from repo root
sys.path.insert(0, str(Path(__file__).parent.parent / "src"))

from phon.reck import reck_decompose, reconstruct_from_ops, ops_to_phon
from phon.parser import parse
from phon.emitter import to_config
from phon.simulator import Simulator

EXAMPLES = Path(__file__).parent


def random_unitary(n, seed):
    rng = np.random.default_rng(seed)
    X = rng.standard_normal((n, n)) + 1j * rng.standard_normal((n, n))
    Q, R = np.linalg.qr(X)
    diag = np.diag(R)
    phases = diag / np.abs(diag)
    return Q * phases


def dft(n):
    U = np.zeros((n, n), dtype=complex)
    for j in range(n):
        for k in range(n):
            U[j, k] = np.exp(-2j * np.pi * j * k / n) / np.sqrt(n)
    return U


def demo_one(label, U, out_stem):
    n = U.shape[0]
    print()
    print("=" * 60)
    print(f"  {label}  (N={n})")
    print("=" * 60)

    ops = reck_decompose(U)
    n_mzi = sum(1 for op in ops if op['type'] == 'mzi_apply')
    n_ps  = sum(1 for op in ops if op['type'] == 'phase_apply')
    print(f"  Decomposition: {n_mzi} MZI + {n_ps} phase shifters = {len(ops)} ops")
    print(f"  Expected:      {n*(n-1)//2} MZI + {n} PS = {n*(n-1)//2 + n}")

    # Method 1: direct reconstruction
    U_hat = reconstruct_from_ops(ops, n)
    err_direct = float(np.linalg.norm(U_hat - U, 'fro'))
    print(f"  [Method 1] reconstruct_from_ops Frobenius = {err_direct:.3e}")
    assert err_direct < 1e-10, f"Method 1 failed: {err_direct}"

    # Method 2: end-to-end via simulator
    result = ops_to_phon(ops, n, "inp")
    cfg = to_config(parse(result['source']))
    max_err_sim = 0.0
    for k in range(n):
        sim = Simulator(cfg)
        x = np.zeros(n, dtype=complex)
        x[k] = 1.0
        sim.tensors["inp"] = x.copy()
        sim.run()
        out = sim.tensors[result['last_name']]
        max_err_sim = max(max_err_sim, float(np.abs(out - U[:, k]).max()))
    print(f"  [Method 2] simulator max column err    = {max_err_sim:.3e}")
    assert max_err_sim < 1e-9, f"Method 2 failed: {max_err_sim}"

    # Save static files
    header = (
        f"// Generated by examples/reck_demo.py\n"
        f"// {label} - Reck 1994 decomposition (N={n})\n"
        f"// Target U saved as {out_stem}_U.npy\n"
        f"// Usage: load U.npy, set sim.tensors['inp'] = basis_vector, then sim.run()\n"
        f"//\n"
    )
    phon_path = EXAMPLES / f"{out_stem}.phon"
    npy_path = EXAMPLES / f"{out_stem}_U.npy"
    phon_path.write_text(header + result['source'], encoding="utf-8")
    np.save(npy_path, U)
    print(f"  Saved: {phon_path.name} ({phon_path.stat().st_size} bytes)")
    print(f"  Saved: {npy_path.name} ({npy_path.stat().st_size} bytes)")

    return err_direct, max_err_sim


def main():
    print("Reck 1994 decomposition demo")
    print("=" * 60)

    results = {}

    # 3x3 DFT
    U3 = dft(3)
    results['dft3'] = demo_one("3x3 DFT", U3, "reck_dft3")

    # 4x4 random
    U4 = random_unitary(4, seed=42)
    results['u4'] = demo_one("4x4 random U(4)", U4, "reck_full_4x4")

    # 8x8 random
    U8 = random_unitary(8, seed=42)
    results['u8'] = demo_one("8x8 random U(8)", U8, "reck_full_8x8")

    print()
    print("=" * 60)
    print("  SUMMARY")
    print("=" * 60)
    for name, (err_d, err_s) in results.items():
        print(f"  {name:12s}  direct={err_d:.3e}  simulator={err_s:.3e}")
    print()
    print("  All decompositions verified.")
    print(f"  Static files written to: {EXAMPLES}")


if __name__ == "__main__":
    main()