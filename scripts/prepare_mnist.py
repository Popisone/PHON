"""Prepare MNIST weights for PHON Phase 5.

Downloads MNIST .npz directly (no pandas needed), trains a
784 -> 128 (relu) -> 10 (softmax) MLP with sklearn, exports
weights as .npy compatible with the PHON simulator.

Run once:  python scripts/prepare_mnist.py
Then:      pytest tests/test_phase5_mnist.py -v
"""
from __future__ import annotations

import io
import sys
import urllib.request
from pathlib import Path

import numpy as np
from sklearn.neural_network import MLPClassifier

OUT = Path(__file__).resolve().parent.parent / "examples" / "mnist"
OUT.mkdir(parents=True, exist_ok=True)

MNIST_URL = "https://storage.googleapis.com/tensorflow/tf-keras-datasets/mnist.npz"
CACHE = OUT / "mnist.npz"


def _download_mnist() -> bytes:
    if CACHE.exists():
        print(f"      Using cached {CACHE.name} ({CACHE.stat().st_size // 1024} KB)")
        return CACHE.read_bytes()
    print(f"      Downloading {MNIST_URL} ...")
    with urllib.request.urlopen(MNIST_URL, timeout=120) as r:
        data = r.read()
    CACHE.write_bytes(data)
    print(f"      Cached {CACHE.name} ({len(data) // 1024} KB)")
    return data


def main() -> int:
    print("[1/4] Loading MNIST ...")
    data = _download_mnist()
    with np.load(io.BytesIO(data)) as f:
        X_train = f["x_train"].reshape(-1, 784).astype(np.float32) / 255.0
        y_train = f["y_train"].astype(np.int64)
        X_test = f["x_test"].reshape(-1, 784).astype(np.float32) / 255.0
        y_test = f["y_test"].astype(np.int64)
    print(f"      Train: {X_train.shape}   Test: {X_test.shape}")

    print("[2/4] Sanity check (first 10 labels):", y_train[:10].tolist())

    print("[3/4] Training 784 -> 128 (relu) -> 10 (softmax) ...")
    clf = MLPClassifier(
        hidden_layer_sizes=(128,),
        activation="relu",
        solver="adam",
        max_iter=20,
        random_state=42,
        verbose=False,
    )
    clf.fit(X_train, y_train)

    train_acc = clf.score(X_train, y_train)
    test_acc = clf.score(X_test, y_test)
    print(f"      Train accuracy: {train_acc:.4f}")
    print(f"      Test  accuracy: {test_acc:.4f}")

    print("[4/4] Exporting weights (.npy, output x input for PHON) ...")
    # sklearn: coefs_[i] has shape (n_in, n_out) -> transpose for PHON
    w1 = clf.coefs_[0].T.astype(np.float64)         # (128, 784)
    b1 = clf.intercepts_[0].astype(np.float64)      # (128,)
    w2 = clf.coefs_[1].T.astype(np.float64)         # (10, 128)
    b2 = clf.intercepts_[1].astype(np.float64)      # (10,)

    np.save(OUT / "w1.npy", w1)
    np.save(OUT / "w1_bias.npy", b1)
    np.save(OUT / "w2.npy", w2)
    np.save(OUT / "w2_bias.npy", b2)

    x100 = X_test[:100].astype(np.float64)
    y100 = y_test[:100]
    sklearn_preds = clf.predict(x100).astype(np.int64)
    np.save(OUT / "x_test.npy", x100)
    np.save(OUT / "y_test.npy", y100)
    np.save(OUT / "y_pred_sklearn.npy", sklearn_preds)

    (OUT / "README.md").write_text(
        "# MNIST weights for PHON Phase 5\n\n"
        "Generated by `scripts/prepare_mnist.py`.\n\n"
        f"- Architecture: 784 -> 128 (relu) -> 10 (softmax)\n"
        f"- sklearn MLPClassifier, adam, 20 epochs\n"
        f"- Train accuracy: {train_acc:.4f}\n"
        f"- Test accuracy: {test_acc:.4f}\n"
        f"- Weights stored as (output x input) for PHON simulator\n"
        f"- 100 test samples + true labels + sklearn predictions\n",
        encoding="utf-8",
    )

    print(f"\n      Written to {OUT}:")
    for f in sorted(OUT.glob("*.npy")):
        arr = np.load(f)
        print(f"        {f.name:20s} {str(arr.shape):15s} {arr.dtype}")
    return 0


if __name__ == "__main__":
    sys.exit(main())